/**
 * Returns translation object for given language code with smart fallback.
 */
export function getTranslations(langCode: string): TranslationDictionary {
  if (TRANSLATIONS[langCode]) {
    return TRANSLATIONS[langCode];
  }
  if (langCode === 'zh-TW' && TRANSLATIONS.zh) {
    return TRANSLATIONS.zh;
  }
  // If language dictionary is pending, fallback to English then Arabic
  return TRANSLATIONS.en || TRANSLATIONS.ar;
}
